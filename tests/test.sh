#!/bin/sh
# Tests for bin/wsl-ssh-config-sync. Run from this directory: ./test.sh
# Uses temporary files only; never touches the real ~/.ssh or /mnt/c.
set -u

script=$(cd "$(dirname "$0")/.." && pwd)/bin/wsl-ssh-config-sync
header='# Generated by wsl-ssh-config-sync from ~/.ssh/config in WSL. Do not edit: changes here are overwritten.'
# Stop here if mktemp fails: an empty $work would make the cleanup below remove /case.
work=$(mktemp -d) && [ -d "$work" ] || { echo "mktemp -d failed" >&2; exit 1; }
trap 'chmod -R u+w "$work" 2>/dev/null; rm -rf "$work"' EXIT
failures=0

fail() { echo "FAIL: $1" >&2; failures=$((failures + 1)); }

# Fresh HOME and Windows .ssh directory for each case.
setup() {
  chmod -R u+w "$work" 2>/dev/null
  rm -rf "$work/case"
  mkdir -p "$work/case/home/.ssh" "$work/case/win"
  src="$work/case/home/.ssh/config"
  dst="$work/case/win/wsl-synced-config"
  printf 'Host a\n  HostName 192.0.2.1\n' > "$src"
  { printf '%s\n' "$header"; cat "$src"; } > "$work/expected"
}

run() {
  env HOME="$work/case/home" WSL_SSH_CONFIG_SYNC_TARGET="$dst" "$script" 2>/dev/null
}

# A missing target setting must stop with exit 2 instead of guessing a path.
setup
env -u WSL_SSH_CONFIG_SYNC_TARGET HOME="$work/case/home" "$script" 2>/dev/null
[ $? -eq 2 ] || fail "unset target should exit 2"
[ -z "$(ls -A "$work/case/win")" ] || fail "unset target should not write anything"

# First run: the generated file is created as the header followed by ~/.ssh/config.
setup
run
[ $? -eq 0 ] || fail "first run should exit 0"
cmp -s "$dst" "$work/expected" || fail "first run did not write header + source"
[ "$(ls -A "$work/case/win")" = "wsl-synced-config" ] || fail "first run left a temporary file beside the target"

# Later runs replace a file this tool generated with the new content.
setup
printf '%s\nHost old\n' "$header" > "$dst"
run
[ $? -eq 0 ] || fail "regenerating should exit 0"
cmp -s "$dst" "$work/expected" || fail "regenerating did not replace the old generated file"

# A file this tool did not generate (for example the hand-edited Windows config) is never overwritten.
setup
printf 'Host windows-only\n' > "$dst"
cp "$dst" "$work/dst.before"
# A neighbouring file the tool did not create must survive too.
printf 'keep\n' > "$dst.wsl-ssh-config-sync.tmp"
run
[ $? -eq 1 ] || fail "foreign target should exit 1"
cmp -s "$dst" "$work/dst.before" || fail "foreign target was overwritten"
[ -e "$dst.wsl-ssh-config-sync.tmp" ] || fail "refused run removed a file it did not create"

# A failed write leaves the existing generated file intact. chmod cannot block root, so skip there.
if [ "$(id -u)" -ne 0 ]; then
  setup
  printf '%s\nHost old\n' "$header" > "$dst"
  cp "$dst" "$work/dst.before"
  chmod a-w "$work/case/win"
  run
  [ $? -ne 0 ] || fail "unwritable target directory should exit non-zero"
  cmp -s "$dst" "$work/dst.before" || fail "failed write changed the existing file"
fi

if [ "$failures" -eq 0 ]; then
  echo "all tests passed"
else
  echo "$failures test(s) failed" >&2
  exit 1
fi
